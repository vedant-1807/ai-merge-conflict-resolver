"""Aggregate eval JSONL output into the headline metrics table."""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from mergeagent.eval.scenarios import read_jsonl


def _pct(n: float, d: float) -> str:
    return f"{100 * n / d:.1f}%" if d else "n/a"


def summarise_runs(rows: list[dict[str, Any]]) -> dict[str, Any]:
    attempts = sum(r["attempts"] or 0 for r in rows)
    cost = sum(r["cost_usd"] or 0 for r in rows)
    sims = [r["similarity"] for r in rows if r.get("similarity") is not None]
    return {
        "n": len(rows),
        "verified": sum(1 for r in rows if r["verified"]),
        "cost": cost,
        "attempts": attempts,
        "cost_per_attempt": cost / attempts if attempts else 0.0,
        "mean_similarity": sum(sims) / len(sims) if sims else None,
        "exact": sum(1 for r in rows if r.get("exact_match")),
    }


def write_report(directory: Path, out: Path) -> str:
    routed = read_jsonl(directory / "routed.jsonl")
    fixed = read_jsonl(directory / "fixed.jsonl")
    mutations = read_jsonl(directory / "mutations.jsonl")
    lines = [
        "# Evaluation results",
        "",
        "Generated by `make eval-report` from `eval-results/`.",
        "",
    ]

    if routed:
        s = summarise_runs(routed)
        lines += [
            "## Test-verified resolution rate", "",
            "| Metric | Value |", "|---|---|",
            f"| Merge scenarios | {s['n']} from {len({r['repo'] for r in routed})} repositories |",
            f"| Test-verified resolutions | {s['verified']} ({_pct(s['verified'], s['n'])}) |",
            f"| Exact match with human merge | {s['exact']} ({_pct(s['exact'], s['n'])}) |",
            f"| Mean similarity to human merge | {s['mean_similarity']:.3f} |" if s["mean_similarity"] is not None else "| Mean similarity | n/a |",
            f"| Total LLM cost | ${s['cost']:.2f} |", "",
            "| Repository | Scenarios | Verified |", "|---|---|---|",
        ]  # fmt: skip
        per_repo: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for r in routed:
            per_repo[r["repo"]].append(r)
        for repo, rs in sorted(per_repo.items()):
            v = sum(1 for r in rs if r["verified"])
            lines.append(f"| {repo} | {len(rs)} | {v} ({_pct(v, len(rs))}) |")
        lines.append("")

    if routed and fixed:
        r, f = summarise_runs(routed), summarise_runs(fixed)
        saving = 1 - r["cost_per_attempt"] / f["cost_per_attempt"] if f["cost_per_attempt"] else 0.0
        lines += [
            "## Model routing vs fixed-model baseline", "",
            "| Mode | Verified | Cost / attempt |", "|---|---|---|",
            f"| Routed | {_pct(r['verified'], r['n'])} | ${r['cost_per_attempt']:.4f} |",
            f"| Fixed ({fixed[0]['mode'].removeprefix('fixed:')}) | {_pct(f['verified'], f['n'])} | ${f['cost_per_attempt']:.4f} |",
            "", f"**Cost per attempt reduction: {100 * saving:.1f}%**", "",
        ]  # fmt: skip

    if mutations:
        det = sum(1 for m in mutations if m["detected"])
        ops = Counter(m["operator"] for m in mutations)
        det_ops = Counter(m["operator"] for m in mutations if m["detected"])
        lines += [
            "## Injected behavioural regressions", "",
            f"**Detected {det}/{len(mutations)} ({_pct(det, len(mutations))})** before a PR would be opened.", "",
            "| Operator | Mutants | Detected |", "|---|---|---|",
            *[f"| {op} | {n} | {_pct(det_ops[op], n)} |" for op, n in ops.most_common()], "",
        ]  # fmt: skip

    if len(lines) == 4:
        lines.append("_No results yet. Run `make eval-mine eval-run eval-cost eval-mutate` first._")
    text = "\n".join(lines) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return text
